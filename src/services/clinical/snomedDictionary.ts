export interface SnomedMatchResult {
  code: string;
  display: string;
  preferredTerm: string;
  fsn: string;
  matchedText: string;
  confidence: number;
  hierarchy: string;
  start: number;
  end: number;
}

// Build precompiled lookup structures
interface SynonymMapItem {
  entry: SnomedLexiconEntry;
  synonym: string;
}

const SORTED_SYNONYM_ITEMS: SynonymMapItem[] = (() => {
  const items: SynonymMapItem[] = [];
  for (const entry of SNOMED_LEXICON) {
    for (const syn of entry.synonyms) {
      items.push({ entry, synonym: syn.toLowerCase() });
    }
  }
  // Sort descending by synonym length so longer multi-word phrases match first
  items.sort((a, b) => b.synonym.length - a.synonym.length);
  return items;
})();

/**
 * Escapes characters for safe regular expression compilation.
 */
function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Searches text for SNOMED CT concepts with boundary matching and deduplication.
 */
export function lookupSnomedConcepts(
  text: string,
  isNegatedSpan?: (start: number, end: number) => boolean,
): SnomedMatchResult[] {
  if (!text || text.trim().length === 0) {
    return [];
  }

  const results: SnomedMatchResult[] = [];
  const matchedCodes = new Set<string>();
  const matchedCharSpans: Array<[number, number]> = [];

  for (const item of SORTED_SYNONYM_ITEMS) {
    // If concept already matched and we want deduplicated concepts
    if (matchedCodes.has(item.entry.code)) {
      continue;
    }

    const pattern = new RegExp(`\\b${escapeRegex(item.synonym)}\\b`, 'gi');
    let match: RegExpExecArray | null = pattern.exec(text);

    while (match !== null) {
      const start = match.index;
      const end = start + match[0].length;

      // Check if this span overlaps with a previously matched longer term
      const overlaps = matchedCharSpans.some(([s, e]) => start < e && end > s);
      if (!overlaps) {
        // Check if negated
        const negated = isNegatedSpan ? isNegatedSpan(start, end) : false;
        if (!negated) {
          matchedCodes.add(item.entry.code);
          matchedCharSpans.push([start, end]);
          results.push({
            code: item.entry.code,
            display: item.entry.display,
            preferredTerm: item.entry.term,
            fsn: item.entry.fsn,
            matchedText: match[0],
            confidence: 0.98,
            hierarchy: item.entry.hierarchy,
            start,
            end,
          });
          break; // move to next concept
        }
      }

      match = pattern.exec(text);
    }
  }

  return results;
}
